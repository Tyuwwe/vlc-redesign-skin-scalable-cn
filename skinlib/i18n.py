def translate(text, language):
    if language == "en":
        return text
    if language != "zh-CN":
        raise ValueError("language must be 'en' or 'zh-CN'")
    try:
        return _ZH_CN[text]
    except KeyError:
        raise KeyError(f"Missing zh-CN translation for {text!r}") from None
